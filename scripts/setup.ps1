#requires -Version 7
<#
.SYNOPSIS
  Sets up the tui-kanban database. Safe to run repeatedly.

.DESCRIPTION
  After one run, all of the following hold (docs/architecture.md section 3.3):
    1. .env exists and holds the passwords of the three roles.
    2. Container kb-postgres is running and healthy (127.0.0.1:55432).
    3. ~/.config/kb/config.toml exists and holds only the writer and reader URLs.
    4. The roles exist and the schema is current in databases kanban and kanban_test.

  The admin URL is never written to the config file: agents read that file
  (docs/board-v2.md section 15.4). The script sets KB_ADMIN_URL only inside its own process
  for `kb db migrate`, and prints how to set it in a shell afterwards.

  Re-running never changes existing passwords or data. Passwords are taken, in order, from
  .env, then from an existing ~/.config/kb/config.toml (the admin password also from an old
  admin_url there, or from $env:KB_ADMIN_URL), and only generated when none has them.

.PARAMETER SkipBuild
  Do not run `cargo build --release`; use the existing target/release/kb.exe.

.PARAMETER Yes
  Pass --yes to `kb db migrate --database kanban`: apply pending migrations even though the
  database already has boards (docs/board-v2.md section 15.5). Without it, the script stops
  after printing the plan. kanban_test is always migrated with --yes.
#>
[CmdletBinding()]
param(
    [switch]$SkipBuild,
    [switch]$Yes
)

$ErrorActionPreference = 'Stop'
$PSNativeCommandUseErrorActionPreference = $false
Set-StrictMode -Version Latest

$Root = Split-Path -Parent $PSScriptRoot
$EnvFile = Join-Path $Root '.env'
$ComposeFile = Join-Path $Root 'docker-compose.yml'
$ConfigDir = Join-Path $HOME '.config/kb'
$ConfigFile = Join-Path $ConfigDir 'config.toml'
$Container = 'kb-postgres'
$Port = 55432
$Roles = [ordered]@{
    KB_ADMIN_PASSWORD  = 'kb_admin'
    KB_WRITER_PASSWORD = 'kb_writer'
    KB_READER_PASSWORD = 'kb_reader'
}
$Utf8NoBom = [System.Text.UTF8Encoding]::new($false)

function Write-Step([string]$Message) { Write-Host "==> $Message" -ForegroundColor Cyan }

function Assert-ExitCode([string]$What) {
    if ($LASTEXITCODE -ne 0) { throw "$What failed (exit code $LASTEXITCODE)" }
}

function New-Password {
    # Alphanumeric only, so the password needs no escaping inside a connection URL.
    $chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789'
    -join (1..32 | ForEach-Object {
        $chars[[System.Security.Cryptography.RandomNumberGenerator]::GetInt32($chars.Length)]
    })
}

function Read-EnvFile([string]$Path) {
    $values = @{}
    if (Test-Path $Path) {
        foreach ($line in Get-Content -LiteralPath $Path -Encoding utf8) {
            if ($line -match '^\s*([A-Z_]+)\s*=\s*(.*?)\s*$') { $values[$Matches[1]] = $Matches[2] }
        }
    }
    return $values
}

function Read-ConfigPasswords([string]$Path) {
    # An old config file may still hold admin_url; it is only read here, never written back.
    $values = @{}
    if (Test-Path $Path) {
        $text = Get-Content -LiteralPath $Path -Raw -Encoding utf8
        foreach ($key in $Roles.Keys) {
            $role = $Roles[$key]
            if ($text -match "postgres://${role}:([^@`"]+)@") { $values[$key] = [uri]::UnescapeDataString($Matches[1]) }
        }
    }
    if ($env:KB_ADMIN_URL -and -not $values.ContainsKey('KB_ADMIN_PASSWORD') -and
        $env:KB_ADMIN_URL -match '^postgres(ql)?://kb_admin:([^@]+)@') {
        $values['KB_ADMIN_PASSWORD'] = [uri]::UnescapeDataString($Matches[2])
    }
    return $values
}

function Test-DataVolume {
    docker volume inspect kb-pgdata *> $null
    return ($LASTEXITCODE -eq 0)
}

# --- 1. Passwords and .env ---------------------------------------------------------------
Write-Step 'Passwords (.env)'
$fromEnv = Read-EnvFile $EnvFile
$fromConfig = Read-ConfigPasswords $ConfigFile
$passwords = [ordered]@{}
foreach ($key in $Roles.Keys) {
    if ($fromEnv.ContainsKey($key) -and $fromEnv[$key]) {
        $passwords[$key] = $fromEnv[$key]
    } elseif ($fromConfig.ContainsKey($key) -and $fromConfig[$key]) {
        $passwords[$key] = $fromConfig[$key]
        Write-Host "    $key recovered from $ConfigFile or KB_ADMIN_URL"
    } elseif ($key -eq 'KB_ADMIN_PASSWORD' -and (Test-DataVolume)) {
        # The existing database only accepts its original admin password.
        throw "KB_ADMIN_PASSWORD is not in $EnvFile, and volume kb-pgdata already exists. Restore .env, or set KB_ADMIN_URL in this shell, and run again."
    } else {
        $passwords[$key] = New-Password
        Write-Host "    $key generated"
    }
}
$envText = "# Generated by scripts/setup.ps1. Do not commit.`n" +
    (($passwords.Keys | ForEach-Object { "$_=$($passwords[$_])" }) -join "`n") + "`n"
$oldEnvText = if (Test-Path $EnvFile) { Get-Content -LiteralPath $EnvFile -Raw -Encoding utf8 } else { '' }
if ($oldEnvText -ne $envText) {
    [System.IO.File]::WriteAllText($EnvFile, $envText, $Utf8NoBom)
    Write-Host "    wrote $EnvFile"
} else {
    Write-Host "    $EnvFile unchanged"
}

# --- 2. Container ---------------------------------------------------------------------------
Write-Step "Container $Container"
docker info --format '{{.ServerVersion}}' *> $null
if ($LASTEXITCODE -ne 0) { throw 'Docker engine is not reachable. Start Docker Desktop and run this script again.' }

docker compose --file $ComposeFile --env-file $EnvFile --project-directory $Root up --detach --wait --wait-timeout 90
Assert-ExitCode 'docker compose up'
$health = docker inspect --format '{{.State.Health.Status}}' $Container
Assert-ExitCode 'docker inspect'
if ($health -ne 'healthy') { throw "container $Container is $health, expected healthy" }
Write-Host "    $Container is healthy on 127.0.0.1:$Port"

# --- 3. Config file -------------------------------------------------------------------------
Write-Step "Config ($ConfigFile)"
function Get-Url([string]$Role, [string]$Password) { "postgres://${Role}:$Password@127.0.0.1:$Port/kanban" }
# No admin_url: kb ignores it, and agents read this file (docs/board-v2.md section 15.4).
$configText = @"
# Generated by tui-kanban scripts/setup.ps1.
# The admin URL is not kept here: set KB_ADMIN_URL in the shell for kb db migrate.
[database]
writer_url = "$(Get-Url 'kb_writer' $passwords.KB_WRITER_PASSWORD)"
reader_url = "$(Get-Url 'kb_reader' $passwords.KB_READER_PASSWORD)"

"@ -replace "`r`n", "`n"
New-Item -ItemType Directory -Force -Path $ConfigDir | Out-Null
$oldConfigText = if (Test-Path $ConfigFile) { Get-Content -LiteralPath $ConfigFile -Raw -Encoding utf8 } else { '' }
if ($oldConfigText -ne $configText) {
    [System.IO.File]::WriteAllText($ConfigFile, $configText, $Utf8NoBom)
    Write-Host "    wrote $ConfigFile"
} else {
    Write-Host "    $ConfigFile unchanged"
}

# --- 4. Build kb and migrate ----------------------------------------------------------------
$Kb = Join-Path $Root 'target/release/kb.exe'
if (-not $SkipBuild) {
    Write-Step 'cargo build --release'
    cargo build --release --manifest-path (Join-Path $Root 'Cargo.toml') --package kb
    Assert-ExitCode 'cargo build'
}
if (-not (Test-Path $Kb)) { throw "$Kb not found; run without -SkipBuild" }


# KB_ADMIN_URL lives only in this process (and the kb processes it starts).
$env:KB_ADMIN_URL = Get-Url 'kb_admin' $passwords.KB_ADMIN_PASSWORD
try {
    foreach ($database in @('kanban', 'kanban_test')) {
        $migrateArgs = @('db', 'migrate', '--database', $database)
        if ($database -eq 'kanban_test' -or $Yes) { $migrateArgs += '--yes' }
        Write-Step "kb $($migrateArgs -join ' ')"
        & $Kb @migrateArgs
        if ($LASTEXITCODE -ne 0 -and $database -eq 'kanban' -and -not $Yes) {
            throw "kb db migrate --database kanban stopped (see the plan above). Review it, then run: pwsh scripts/setup.ps1 -SkipBuild -Yes"
        }
        Assert-ExitCode "kb db migrate --database $database"
    }
} finally {
    Remove-Item Env:KB_ADMIN_URL -ErrorAction SilentlyContinue
}

Write-Step 'kb db status'
& $Kb db status
Assert-ExitCode 'kb db status'

Write-Host ''
Write-Host "Done. Add $(Split-Path -Parent $Kb) to PATH, or call $Kb directly." -ForegroundColor Green
Write-Host ''
Write-Host 'kb db migrate (and cargo test) need KB_ADMIN_URL; it is not in the config file.'
Write-Host "Set it only in the shell where you need it. The password is KB_ADMIN_PASSWORD in $EnvFile."
Write-Host "  PowerShell:  `$env:KB_ADMIN_URL = 'postgres://kb_admin:<KB_ADMIN_PASSWORD>@127.0.0.1:$Port/kanban'"
Write-Host "  bash/zsh:    export KB_ADMIN_URL='postgres://kb_admin:<KB_ADMIN_PASSWORD>@127.0.0.1:$Port/kanban'"
